private struct QuitInsight: Identifiable, Equatable {
    let id = UUID()
    let category: String
    let title: String
    let body: String

    init(_ category: String, _ title: String, _ body: String) {
        self.category = category
        self.title = title
        self.body = body
    }

    var preview: String {
        let limit = 72
        guard body.count > limit else { return body }
        return String(body.prefix(limit)) + "……"
    }
}

